#!/usr/bin/env node

import fs from "fs";
import path from "path";
import { pathToFileURL } from "node:url";

import glob from "fast-glob";

// Each story declares its metadata in a side-effect-free `<story>.meta.ts` sidecar (the `.test.ts`
// registers Playwright tests on import and can't be imported here). Requires Node >= 24, which strips
// the TypeScript types when importing these `.ts` modules.
const META_GLOB = "tests/e2e/stories/[^_]*.meta.ts";
const OUT_PATH = path.resolve("src/framework/internal/components/TutorialsDialog/tutorials.generated.ts");

const REQUIRED_FIELDS = ["slug", "category", "title", "description"];
const SLUG_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

export async function generateTutorialsManifest() {
    const metaFiles = (await glob(META_GLOB, { cwd: process.cwd() })).sort();

    const entries = [];
    const errors = [];
    for (const file of metaFiles) {
        let meta;
        try {
            ({ meta } = await import(pathToFileURL(path.resolve(file)).href));
        } catch (err) {
            errors.push(`${file}: ${err instanceof Error ? err.message : String(err)}`);
            continue;
        }

        if (!meta || typeof meta !== "object") {
            errors.push(`${file}: must export a "meta" object.`);
            continue;
        }
        const missing = REQUIRED_FIELDS.filter((field) => !meta[field]);
        if (missing.length > 0) {
            errors.push(`${file}: missing required tutorialMeta field(s): ${missing.join(", ")}.`);
            continue;
        }
        if (!SLUG_RE.test(meta.slug)) {
            errors.push(
                `${file}: slug "${meta.slug}" must be kebab-case (lowercase letters, digits and hyphens only).`,
            );
            continue;
        }
        entries.push({ ...meta, sourceFile: file });
    }

    const slugsSeen = new Map();
    for (const entry of entries) {
        const usedBy = slugsSeen.get(entry.slug);
        if (usedBy) {
            errors.push(`Duplicate tutorial slug "${entry.slug}" used by both ${usedBy} and ${entry.sourceFile}.`);
        }
        slugsSeen.set(entry.slug, entry.sourceFile);
    }

    if (errors.length > 0) {
        console.error("[CLI] ❌ Tutorial metadata violations found:");
        for (const message of errors) {
            console.error(`  - ${message}`);
        }
        process.exit(1);
    }

    entries.sort(
        (a, b) =>
            a.category.localeCompare(b.category) ||
            (a.order ?? Infinity) - (b.order ?? Infinity) ||
            a.title.localeCompare(b.title),
    );

    const entryLines = entries.map(
        (entry) =>
            `    {\n` +
            `        slug: "${entry.slug}",\n` +
            `        category: ${JSON.stringify(entry.category)},\n` +
            `        title: ${JSON.stringify(entry.title)},\n` +
            `        description: ${JSON.stringify(entry.description)},\n` +
            `    },`,
    );

    const fileContent =
        `// AUTO-GENERATED FILE. DO NOT EDIT.\n` +
        `// Generated by generate-tutorials-manifest CLI from metadata declared in tests/e2e/stories/*.meta.ts\n\n` +
        `export type TutorialVideo = {\n` +
        `    slug: string;\n` +
        `    category: string;\n` +
        `    title: string;\n` +
        `    description: string;\n` +
        `};\n\n` +
        `export const TUTORIAL_VIDEOS: TutorialVideo[] = [\n${entryLines.join("\n")}\n];\n`;

    fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
    fs.writeFileSync(OUT_PATH, fileContent, "utf-8");

    console.log(`[CLI] ✅ Tutorials manifest written to ${OUT_PATH} (${entries.length} video(s)).`);
}

generateTutorialsManifest();
