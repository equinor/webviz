#!/usr/bin/env node

import fs from "fs";
import path from "path";
import glob from "fast-glob";

import { parseTutorialMeta } from "./lib/parseTutorialMeta.js";

/** Public, anonymously-readable container the e2e_recordings CI workflow publishes videos to. */
const TUTORIAL_VIDEOS_BASE_URL = "https://webviz.blob.core.windows.net/tutorial-videos";

const STORIES_GLOB = "tests/e2e/stories/[^_]*.test.ts";
const OUT_PATH = path.resolve("src/framework/internal/components/TutorialsDialog/tutorials.generated.ts");

export async function generateTutorialsManifest() {
    const storyFiles = (await glob(STORIES_GLOB, { cwd: process.cwd() })).sort();

    const entries = [];
    const errors = [];
    for (const file of storyFiles) {
        try {
            entries.push(parseTutorialMeta(path.resolve(file)));
        } catch (err) {
            errors.push(err instanceof Error ? err.message : String(err));
        }
    }

    const slugsSeen = new Map();
    for (const entry of entries) {
        const usedBy = slugsSeen.get(entry.slug);
        if (usedBy) {
            errors.push(`Duplicate tutorial slug "${entry.slug}" used by both ${usedBy} and ${entry.sourceFile}.`);
        }
        slugsSeen.set(entry.slug, entry.sourceFile);
    }

    if (errors.length > 0) {
        console.error("[CLI] ❌ Tutorial metadata violations found:");
        for (const message of errors) {
            console.error(`  - ${message}`);
        }
        process.exit(1);
    }

    entries.sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

    const entryLines = entries.map(
        (entry) =>
            `    {\n` +
            `        slug: "${entry.slug}",\n` +
            `        category: ${JSON.stringify(entry.category)},\n` +
            `        title: ${JSON.stringify(entry.title)},\n` +
            `        description: ${JSON.stringify(entry.description)},\n` +
            `        videoUrl: "${TUTORIAL_VIDEOS_BASE_URL}/${entry.slug}.webm",\n` +
            `        thumbnailUrl: "${TUTORIAL_VIDEOS_BASE_URL}/${entry.slug}.png",\n` +
            `    },`,
    );

    const fileContent =
        `// AUTO-GENERATED FILE. DO NOT EDIT.\n` +
        `// Generated by generate-tutorials-manifest CLI from metadata declared in tests/e2e/stories/*.test.ts\n\n` +
        `export type TutorialVideo = {\n` +
        `    slug: string;\n` +
        `    category: string;\n` +
        `    title: string;\n` +
        `    description: string;\n` +
        `    videoUrl: string;\n` +
        `    thumbnailUrl: string;\n` +
        `};\n\n` +
        `export const TUTORIAL_VIDEOS: TutorialVideo[] = [\n${entryLines.join("\n")}\n];\n`;

    fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
    fs.writeFileSync(OUT_PATH, fileContent, "utf-8");

    console.log(`[CLI] ✅ Tutorials manifest written to ${OUT_PATH} (${entries.length} video(s)).`);
}

generateTutorialsManifest();
